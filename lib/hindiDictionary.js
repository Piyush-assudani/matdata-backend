  fixedText = fixedText.replace(/भंवरसिह/g, 'भंवर सिंह');
  fixedText = fixedText.replace(/डूंगरसिह/g, 'डूंगर सिंह');
  fixedText = fixedText.replace(/सावलराम/g, 'सांवलराम');
  fixedText = fixedText.replace(/सावलाराम/g, 'सांवलाराम');
  fixedText = fixedText.replace(/सवरू?प/g, 'स्वरूप');
