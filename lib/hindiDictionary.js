function fixCorruptedHindi(text) {
  if (!text) return text;
  
  let fixedText = text;
  
  // Replace whole words based on dictionary
  const words = fixedText.split(' ');
  const correctedWords = words.map(word => {
    return HINDI_MAP[word] || word;
  });
  
  fixedText = correctedWords.join(' ');
  
  // Apply partial fixes for common patterns (longer first)
  const patternKeys = Object.keys(HINDI_MAP).filter(k => k.length >= 4).sort((a, b) => b.length - a.length);
  for (const k of patternKeys) {
    if (fixedText.includes(k)) {
      fixedText = fixedText.split(k).join(HINDI_MAP[k]);
    }
  }

  // Common suffix / prefix corrections
  fixedText = fixedText.replace(/लरल(?=\s|$)/g, "लाल");
  fixedText = fixedText.replace(/ररम(?=\s|$)/g, "राम");
  fixedText = fixedText.replace(/दकरल(?=\s|$)/g, "देवी");
  fixedText = fixedText.replace(/कचमरर(?=\s|$)/g, "कुमार");
  fixedText = fixedText.replace(/पकरश(?=\s|$)/g, "प्रकाश");
  
  return fixedText.trim();
}

