  fixedText = fixedText.replace(/प्रेपनाथ/g, 'प्रेमनाथ');
  fixedText = fixedText.replace(/प्रेप नाथ/g, 'प्रेमनाथ');
  fixedText = fixedText.replace(/प्रेप/g, 'प्रेम');
  fixedText = fixedText.replace(/ह[ड़ड]मानराम/g, 'हड़मानराम');
  fixedText = fixedText.replace(/ह[ड़ड]मानाराम/g, 'हड़मानाराम');
  fixedText = fixedText.replace(/ह[ड़ड]मान/g, 'हड़मान');
  fixedText = fixedText.replace(/ह[ड़ड]माना/g, 'हड़माना');
